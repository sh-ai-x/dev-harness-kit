#!/usr/bin/env python3
"""maintenance_gate.py — CI maintenance gate logic.

The `.github/workflows/maintenance.yml` workflow calls into this module
for two checks beyond the LLM judge's verdict:

  1. ``extract_verdict(comment_body)`` — parse the `**Verdict:** ...`
     line from the claude-code-action's PR comment. Matches the
     pattern used by `.github/workflows/review.yml` so the two gates
     look identical to operators reading PR comments.

  2. ``docs_updated_ok(changed_files, pr_body)`` — the docs-updated
     sub-gate. Ensures a PR that touches production code also touches
     a corresponding ``docs/`` file, OR justifies "docs not required"
     in the PR body.

Pure functions, no IO, no network. Kept side-effect-free so the
workflow can shell out and the unit tests can run hermetically.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from typing import Dict, Iterable, Mapping, Optional, Tuple

# Production roots: changes here MUST be paired with a docs/ update
# unless the PR body explicitly justifies skipping docs.
#
# Kept in sync with bin/review-local.sh's own touch-probe regex (the
# canonical source; pinned by tests/test_review_yml_touch_probe.py
# against .github/workflows/review.yml's scope job too). All three
# copies previously drifted -- this list was missing bin/, commands/,
# .claude/, .codex/, and .github/ entirely, so a PR that only touched
# e.g. bin/*.sh scripts was never flagged as needing a docs update.
_PROD_ROOTS: Tuple[str, ...] = (
    "bin/", "commands/", "lib/", "tools/", "hooks/", "skills/",
    ".githooks/", ".claude/", ".codex/", ".github/",
)

# Docs files that are auto-managed (regenerated by scripts) and don't
# count as "doc updates" for the docs-updated sub-gate. A PR that
# touches ONLY these files (and prod code) still fails the gate.
_AUTO_MANAGED_DOCS: frozenset = frozenset({
    "docs/stages/STAGES.md",
    "docs/repo/REPOSITORY-MAP.md",
})

# Marker in the PR body that signals "docs not required". Operators
# quote a pre-existing doc path or issue link after the marker.
_DOCS_NOT_REQUIRED_MARKER = "docs-not-required:"

_VERDICT_RE = re.compile(
    r"\*\*Verdict:\*\*\s*(Approve|Blocked|Changes Requested)\b"
)

# Status / verdict → emoji decoration for the audit comment's
# human-facing table. Status "MISSING" / verdict "MISSING" are how the
# GH-Actions emitters report "the LLM judge emitted no verdict line"
# (issue #612: this is a hard fail in gate.yml, not an Approve).
_STATUS_EMOJI: Dict[str, str] = {
    "success": "✅",
    "failure": "❌",
    "MISSING": "❓",
}
_VERDICT_EMOJI: Dict[str, str] = {
    "Approve": "✅",
    "Changes Requested": "⚠️",
    "Blocked": "❌",
    "MISSING": "❓",
}


def extract_verdict(comment_body: str) -> str:
    """Return the LAST ``**Verdict:** <Word>`` line in `comment_body`
    that is NOT inside a markdown code span, or ``""`` when no such
    well-formed verdict line is present.

    The "last match wins" semantics mirror ``scripts/extract-verdict``
    in review.yml: an auto-fix-updated comment supersedes an earlier
    verdict, and a re-run of the action overwrites rather than
    appends.

    Backtick-spanned ``**Verdict:**`` mentions are deliberately
    ignored. LLM judges (security/maintenance) sometimes recap
    earlier review verdicts inside backticks while writing their own
    structural verdict higher up in the body, e.g.:

        **Verdict:** Approve
        ...
        The earlier `**Verdict:** Blocked` (review lens) and
        `**Verdict:** Changes Requested` (maintenance lens) at
        `head_sha=abc123`...

    A naive `re.findall` over the whole body would let the last
    backtick-quoted recap win and silently flip an `Approve` comment
    to `Changes Requested`. Stripping fenced + inline code spans
    first isolates the structural verdict.
    """
    if not comment_body:
        return ""
    # Strip fenced code blocks first (```...```), then inline code
    # spans (`...`). Both can contain backtick-wrapped `**Verdict:**`
    # mentions of prior reviews.
    cleaned = re.sub(r"```.*?```", "", comment_body, flags=re.DOTALL)
    cleaned = re.sub(r"`[^`\n]*`", "", cleaned)
    matches = _VERDICT_RE.findall(cleaned)
    return matches[-1] if matches else ""


def _is_prod_path(path: str) -> bool:
    """True iff `path` lives under one of the production roots."""
    return any(path.startswith(root) for root in _PROD_ROOTS)


def _is_doc_path(path: str, exclude_auto_managed: bool = True) -> bool:
    """True iff `path` lives under docs/ and (when excluding) is not
    one of the auto-managed docs.
    """
    if not path.startswith("docs/"):
        return False
    if exclude_auto_managed and path in _AUTO_MANAGED_DOCS:
        return False
    return True


def _pr_body_justifies_no_docs(pr_body: str) -> bool:
    """True iff the PR body contains the `docs-not-required:` marker.

    Operators quote a pre-existing doc path or an issue link after the
    marker; the gate doesn't try to validate the quoted reference —
    that's a human review concern. The marker itself is the
    deterministic signal that the operator consciously opted out.
    """
    return _DOCS_NOT_REQUIRED_MARKER in (pr_body or "")


def docs_updated_ok(
    changed_files: Iterable[str],
    pr_body: str = "",
) -> Tuple[bool, str]:
    """Return ``(passes, reason)`` for the docs-updated sub-gate.

    Pass conditions (any one):
      - No production paths changed (the PR is docs-only or workflow-
        only).
      - The PR touches at least one non-auto-managed ``docs/`` file.
      - The PR body contains the ``docs-not-required:`` marker.

    Fail: the PR changes a production path AND no docs/ counterpart
    is in the change set AND the PR body doesn't justify skipping.
    """
    files = list(changed_files)
    prod_paths = [p for p in files if _is_prod_path(p)]
    if not prod_paths:
        return True, "no production paths changed"

    # The PR body justification supersedes the file-list check.
    if _pr_body_justifies_no_docs(pr_body):
        return True, "docs-not-required justified in PR body"

    doc_paths = [p for p in files if _is_doc_path(p)]
    if doc_paths:
        return True, f"docs updated: {doc_paths[0]}"

    # Build a concrete reason naming the first prod path so the CI log
    # is actionable — operators can fix the gate failure without
    # re-reading the workflow.
    first_prod = prod_paths[0]
    return False, (
        f"PR changed {first_prod} but no doc under docs/ was updated; "
        f"either add the doc or quote an existing reference in the PR body"
    )


def combine_verdict(
    judge_verdict: str,
    docs_ok: bool,
    docs_reason: str,
) -> Dict[str, object]:
    """Combine (judge_verdict, docs_ok) into a single CI verdict.

    Verdict precedence (worst wins):
      Blocked > Changes Requested > Approve.
    Docs-updated failure downgrades an Approve to Changes Requested
    so the human reviewer notices.
    """
    jv = judge_verdict or ""
    if jv == "Blocked":
        return {"verdict": "Blocked", "docs_ok": docs_ok,
                "reason": docs_reason}
    if not docs_ok:
        # Approve -> Changes Requested when docs are missing.
        return {"verdict": "Changes Requested",
                "docs_ok": False, "reason": docs_reason}
    if jv == "Approve":
        return {"verdict": "Approve", "docs_ok": True,
                "reason": docs_reason}
    if jv == "Changes Requested":
        return {"verdict": "Changes Requested", "docs_ok": docs_ok,
                "reason": docs_reason}
    # Unknown / empty judge verdict is a failed verification, not approval.
    # A missing model response must never become a merge authorization.
    return {"verdict": "Blocked", "docs_ok": docs_ok,
            "reason": f"unknown judge verdict {jv!r}; blocking until verified",
            "warn": True}


def format_audit_body(
    run_id: str,
    job: str,
    status: str,
    verdict: str,
    source: str,
    *,
    extras: Optional[Mapping[str, str]] = None,
) -> str:
    """Build the human-friendly + machine-parseable audit comment.

    The first line carries the marker + the canonical quartet
    (``run=/job=/status=/verdict=``) plus the ``source=`` tail that
    existing emitters use, plus any ``extras=`` the local mirror
    passes (``review=/security=/maintenance=/provider=``). The
    consumer in ``lib/pr_verify.py`` parses ONLY that quartet on
    line 1 — everything below is purely cosmetic, so changes here
    don't affect the verifier.

    Local-only emitters (``bin/review-local.sh``) pass extras so the
    per-skill breakdown lands on the parseable line AND in the
    table. GH emitters leave ``extras=None``.

    Empty fields degrade to ``MISSING`` (the same sentinel the GH
    emitters used pre-refactor) so a missing LLM verdict still
    shows a visible failure signal instead of a blank cell.
    """
    rid = (run_id or "").strip() or "MISSING"
    jb = (job or "").strip() or "MISSING"
    st = (status or "").strip() or "MISSING"
    vd = (verdict or "").strip() or "MISSING"
    src = source or ""  # allow empty source — it's informational

    # Parseable line 1: marker + canonical quartet + source= + extras=.
    # `source=` is always emitted (even when empty) so the parseable
    # quartet stays a stable 5-tuple across emitters — consumers
    # downstream of pr_verify.py may rely on `source=` being present.
    parts = [f"<!-- dev-kit-verdict-audit --> run={rid}", f"job={jb}",
             f"status={st}", f"verdict={vd}", f"source={src}"]
    if extras:
        # Stable key order for byte-identical output (matters for
        # test fixtures and idempotent re-runs).
        for key in sorted(extras):
            parts.append(f"{key}={extras[key]}")
    parseable_line = " ".join(parts)

    # Human-facing markdown table.
    status_emoji = _STATUS_EMOJI.get(st, "")
    verdict_emoji = _VERDICT_EMOJI.get(vd, "")
    header = f"**dev-kit CI verdict — {verdict_emoji} {vd}**"

    rows = [
        ("Run", rid),
        ("Job", jb),
        ("Status", f"{status_emoji} {st}".strip()),
        ("Verdict", f"{verdict_emoji} {vd}".strip()),
        ("Source", src or "MISSING"),
    ]
    if extras:
        # Per-skill breakdown mirrors the parseable-line extras.
        # Keys are rendered Title-Case for the table label.
        for key in sorted(extras):
            label = key.capitalize()
            rows.append((label, extras[key]))

    # Compute label column width: at least 8 chars so the standard
    # five fields breathe, wider if any extras label needs it. The
    # header column matches so pipes align.
    label_width = max(8, max(len(label) for label, _ in rows))
    divider = "-" * label_width
    table_lines = [
        f"| {'Field':<{label_width}}| Value",
        f"|-{divider}-|------------------------",
    ]
    for label, value in rows:
        table_lines.append(f"| {label:<{label_width}}| {value}")

    return f"{parseable_line}\n\n{header}\n\n" + "\n".join(table_lines) + "\n"


def cli_main(argv=None) -> int:
    """CLI entry point.

    Four modes (selected by flag):

      --extract-verdict-from-stdin
          Read stdin, print extracted verdict on stdout.

      --docs-check
          With --changed-files (repeatable) and --pr-body, run the
          docs-updated check and print JSON {docs_ok, reason}.

      --format-audit
          Emit a PR audit comment body (the canonical
          ``<!-- dev-kit-verdict-audit -->`` quartet on line 1 plus a
          human-facing markdown table below). Use with --run / --job /
          --status / --verdict / --source and optional --extra key=value
          pairs.

      (default) — combine_verdict from --judge-verdict +
          --docs-ok + --docs-reason flags, print JSON.
    """
    parser = argparse.ArgumentParser(description="Maintenance gate logic.")
    parser.add_argument("--project-root", default=".")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--extract-verdict-from-stdin",
        action="store_true",
        help="read stdin, print extracted verdict on stdout",
    )
    mode.add_argument(
        "--docs-check",
        action="store_true",
        help="run docs-updated check (use with --changed-files + --pr-body)",
    )
    mode.add_argument(
        "--format-audit",
        action="store_true",
        help="emit a PR audit comment body (use with --run/--job/--status/--verdict/--source)",
    )
    parser.add_argument(
        "--changed-files", action="append", default=[],
        help="changed file path (repeatable)",
    )
    parser.add_argument("--pr-body", default="")
    parser.add_argument("--judge-verdict", default="")
    parser.add_argument("--docs-ok", action="store_true",
                        help="pre-computed docs_ok flag (for combine mode)")
    parser.add_argument("--docs-reason", default="")
    # --format-audit flags
    parser.add_argument("--run", default="",
                        help="[--format-audit] run id (digits or local-$$)")
    parser.add_argument("--job", default="",
                        help="[--format-audit] job name")
    parser.add_argument("--status", default="",
                        help="[--format-audit] job status (success/failure)")
    parser.add_argument("--verdict", default="",
                        help="[--format-audit] judge verdict")
    parser.add_argument("--source", default="lib.maintenance_gate",
                        help="[--format-audit] source tag (default: lib.maintenance_gate)")
    parser.add_argument("--extra", action="append", default=[],
                        help="[--format-audit] extra key=value (repeatable)")
    args = parser.parse_args(argv)

    if args.extract_verdict_from_stdin:
        sys.stdout.write(extract_verdict(sys.stdin.read()))
        sys.stdout.write("\n")
        return 0
    if args.docs_check:
        ok, reason = docs_updated_ok(args.changed_files, args.pr_body)
        sys.stdout.write(json.dumps({"docs_ok": ok, "reason": reason}))
        sys.stdout.write("\n")
        return 0 if ok else 1
    if args.format_audit:
        extras: Dict[str, str] = {}
        for kv in args.extra:
            if "=" in kv:
                k, v = kv.split("=", 1)
                extras[k] = v
        sys.stdout.write(format_audit_body(
            run_id=args.run, job=args.job,
            status=args.status, verdict=args.verdict,
            source=args.source, extras=extras or None,
        ))
        return 0
    # combine mode (default)
    out = combine_verdict(
        judge_verdict=args.judge_verdict,
        docs_ok=bool(args.docs_ok),
        docs_reason=args.docs_reason,
    )
    sys.stdout.write(json.dumps(out))
    sys.stdout.write("\n")
    return 0 if out.get("verdict") == "Approve" else 1


if __name__ == "__main__":
    sys.exit(cli_main())
